/**
 * Operator precedence(Priority) is like the rules of math. 
 * It tells JavaScript which operations to do first. For example, 
 * multiplication is done before addition.
 */

let x = 5 + 3 * 2 // x is 11 (because 3 * 2 is done first)

// You can use parentheses () to change the order:
let y = (5+3) * 2 // y is 16
