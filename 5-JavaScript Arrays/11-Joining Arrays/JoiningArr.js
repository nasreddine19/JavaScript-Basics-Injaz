/**
 * Joining Arrays
 * 
 * Convert array to string with separator
 */

const words = ['Heey', 'Nasreddine', '!'];
const sentence = words.join(' '); // Join with space
console.log(sentence); // 'Heey Nasreddine !'

const JOIN_WITH_COMMA = words.join(','); // Join with comma
console.log(JOIN_WITH_COMMA); // 'Heey,Nasreddine,!'