/** What is Control Structures ?
 * Control Structures is how we tell the computer to make decisions or repeat tasks. 
 * In this chapter, we will learn about different ways to control the flow of our code.
 */

/**
 * The if-else statement helps us make decisions in our code. 
 * It checks if a condition is true or false and then runs the code inside the block.
 */

// Example:
let age = 18;

if (age >= 18) {
  console.log('You are an adult.');
} else {
  console.log('You are a child.');
}