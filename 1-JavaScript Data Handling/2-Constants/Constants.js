/**
 * What is a Constant?
A constant is like a variable, but its value cannot change once it is set. 
It is used for values that should stay the same throughout the program.

 * How to Declare a Constant in JavaScript:
    1- Use the keyword const to create a constant.
    2- Give the constant a name (e.g., PI, PEN_COLOR).
    3- Use the = sign to assign a value to the constant.
 */

// Examples:
const PI = 3.14 // This creates a constant called "PI" and stores the value 3.14.
const PEN_COLOR = 'Black' // This creates a constant called "PEN_COLOR" and stores the value Black.


/**
 * Important Notes:
    1- You cannot change the value of a constant after it is declared.
    2- Constant names are usually written in uppercase to distinguish them from variables.
 */