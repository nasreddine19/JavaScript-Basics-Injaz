/** 
 1- What is a variable?
 A variable is like a container that stores information. 
 You can put data (like numbers, text, or other values) 
 into this container and use it later in your code.

 2- How to Declare a Variable in JavaScript:
    * Use The keyword `let` or `var` to create a variable.
    * Give The variable a name (e.g. userName, score).
    * Use the equals operator (=) to assign a value to the variable.
    * We declare a variables with camelCase Notation.

 3- What is camelCase?
 camelCase is a way of writing variable names where:
    * The 1st word is lowercase.
    * The 1st letter of every following is uppercase.
    * There are no spaces between words.
*/

// Examples:
var userPassword = 123123 // This is the old way to declare a variable with `var` Keyword
let year = 2025 // modern way to declare a variable

let colorName // This Part called the Initialization
colorName = 'Crimson' // This Part Called the Assignment

let userName = 'Nasreddine'; // Initialization and assignment in one step
let score = 100;


/**
 * Important Notes: 
    1- Variable Name cannot start with numbers or contain spaces.
    2- Variable names are case-sensitive (e.g., Name and name are different).
 */
