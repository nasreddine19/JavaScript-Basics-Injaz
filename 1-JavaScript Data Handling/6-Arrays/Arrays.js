/**
 * Arrays in JavaScript
    An array is a variable that can store a list of items. 
    Each item in the array has a number called an index (starting from 0).
 */

// Example:
let colors = ['red', 'crimson', 'purple']
let firstItem = colors[0] // Acces the first item
let secondItem = colors[1] // Acces the second item
let thirdItem = colors[2] // Acces the third item


