/**
 * Objects in JavaScript
    An object is a variable that can store multiple pieces of related data. 
    Each piece of data is stored as a key-value pair. 
 */

// Example:
let profile = {
    userName: 'Nasreddine', // key: 'userName', value: 'Nasreddine'
    userPassword: 13131, // key: 'userPassword', value: 13131
    isStudent: true // key: 'isStudent', value: true
}

//You can access the data using the key: profile.userName gives "Nasreddine".
    let accessData = profile.userName
    console.log(accessData)
//You can also add new data: profile.country = "Algeria";.
    profile.country = 'Algeria'
    console.log(profile)

    
/*
    Key Idea: Objects are variables that store structured data.
*/

